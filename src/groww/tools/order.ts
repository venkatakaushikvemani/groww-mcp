function registerOrderStatusTool(server: any, GROWW_API_KEY: string) {
  server.tool(
    "order_status",
    {
      description: "Get the status of a stock order. Use this tool to check the current status, filled quantity, and other details of an order.",
      groww_order_id: z.string().describe("Order id generated by Groww for an order. Required."),
      segment: z.string().describe("Segment: CASH (Equity), FNO (Futures & Options). Required.")
    },
    async (input: any) => {
      const { groww_order_id, segment } = input;
      if (!groww_order_id || !segment) {
        return {
          content: [{ type: "text", text: "groww_order_id and segment are required." }],
          message: "Please provide both groww_order_id and segment."
        };
      }
      const url = `https://api.groww.in/v1/order/detail/${encodeURIComponent(groww_order_id)}?segment=${encodeURIComponent(segment)}`;
      const response = await fetch(url, {
        method: "GET",
        headers: {
          "Authorization": `Bearer ${GROWW_API_KEY}`,
          "Accept": "application/json"
        }
      });
      const text = await response.text();
      process.stderr.write("Groww Get Order Status API raw response: " + text);
      let data;
      try {
        data = JSON.parse(text);
      } catch (e) {
        return { content: [{ type: "text", text: "Failed to parse JSON from Groww Get Order Status API. Raw response: " + text }], message: "Could not parse order status response. Please try again." };
      }
      const parseResult = GetOrderStatusSchema.safeParse(data);
      if (!parseResult.success) {
        return { content: [{ type: "text", text: "Get Order Status response validation failed:\n" + JSON.stringify(parseResult.error.format(), null, 2) }], message: "Order status fetch failed. Please check your input and try again." };
      }
      return { content: [{ type: "text", text: JSON.stringify(parseResult.data, null, 2) }], message: "Fetched order status. Use the 'modify_order' or 'cancel_order' tools to update or cancel this order if needed." };
    }
  );
}

export function registerOrderTools(server: any, GROWW_API_KEY: string) {
  registerPlaceOrderTool(server, GROWW_API_KEY);
  registerModifyOrderTool(server, GROWW_API_KEY);
  registerCancelOrderTool(server, GROWW_API_KEY);
  registerOrderStatusTool(server, GROWW_API_KEY);
}
